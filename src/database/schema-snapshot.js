import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { QueryTypes } from "sequelize";

import { sequelize } from "../config/database.js";

const filename = fileURLToPath(import.meta.url);
const directory = path.dirname(filename);
const projectRoot = path.resolve(directory, "../..");

export const schemaSnapshotPath = path.join(
  projectRoot,
  "database",
  "schema.latest.sql",
);

const INTERNAL_SCHEMA_TABLES = new Set([
  "sequelizemeta",
  "sequelize_core_seed_meta",
  "sequelize_catalog_seed_meta",
  "sequelize_demo_seed_meta",
]);

function quoteIdentifier(identifier) {
  return `\`${identifier.replaceAll("`", "``")}\``;
}

function normalizeCreateTableStatement(statement) {
  return statement
    .trim()
    .replace(/\sAUTO_INCREMENT=\d+(?=\s|$)/g, "")
    .replace(/\n{3,}/g, "\n\n");
}

function createStatementFromRow(row) {
  return Object.values(row).find(
    (value) =>
      typeof value === "string" &&
      value.trimStart().toUpperCase().startsWith("CREATE TABLE"),
  );
}

function migrationNames(items) {
  return items.map((item) => item.name);
}

/**
 * Writes a deterministic, schema-only MySQL reference snapshot. Migrations
 * remain the source of truth; this output is for review and new-developer
 * visibility only. Seeder metadata tables are intentionally excluded.
 */
export async function writeSchemaSnapshot({
  query = sequelize.query.bind(sequelize),
  outputPath = schemaSnapshotPath,
  makeDirectory = fs.mkdir,
  writeFile = fs.writeFile,
} = {}) {
  const rows = await query(
    `
      SELECT table_name AS tableName
      FROM information_schema.tables
      WHERE table_schema = DATABASE()
        AND table_type = 'BASE TABLE'
      ORDER BY table_name ASC
    `,
    { type: QueryTypes.SELECT },
  );

  const tableNames = rows
    .map((row) => row.tableName)
    .filter((tableName) => typeof tableName === "string")
    .filter(
      (tableName) => !INTERNAL_SCHEMA_TABLES.has(tableName.toLowerCase()),
    );
  const statements = [];

  for (const tableName of tableNames) {
    const createRows = await query(`SHOW CREATE TABLE ${quoteIdentifier(tableName)}`, {
      type: QueryTypes.SELECT,
    });
    const statement = createStatementFromRow(createRows[0] ?? {});

    if (!statement) {
      throw new Error(`Unable to read the schema for table "${tableName}"`);
    }

    const normalized = normalizeCreateTableStatement(statement);
    statements.push(normalized.endsWith(";") ? normalized : `${normalized};`);
  }

  const snapshot = [
    "-- Redress derived schema reference.",
    "-- Generated by npm run db:sync:dev. Do not apply this as a migration.",
    "-- Incremental migrations in src/database/migrations remain the source of truth.",
    "",
    ...statements,
    "",
  ].join("\n\n");

  await makeDirectory(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, snapshot, "utf8");

  return {
    outputPath,
    tableCount: tableNames.length,
    tables: tableNames,
  };
}

export function summarizeMigrationNames(items) {
  return migrationNames(items);
}
